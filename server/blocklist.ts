const blockedSet = new Set(BLOCKED_DOMAINS.map((d) => d.toLowerCase()));

/**
 * Checks if a given hostname or URL matches an ad/tracker domain.
 */
export function isBlocked(urlOrHost: string): boolean {
  try {
    let hostname = urlOrHost;
    if (urlOrHost.includes('://')) {
      hostname = new URL(urlOrHost).hostname;
    }
    hostname = hostname.toLowerCase();

    // Check exact domain
    if (blockedSet.has(hostname)) {
      return true;
    }

    // Check subdomains
    const parts = hostname.split('.');
    for (let i = 0; i < parts.length - 1; i++) {
      const sub = parts.slice(i).join('.');
      if (blockedSet.has(sub)) {
        return true;
      }
    }

    return false;
  } catch {
    return false;
  }
}

/**
 * Strips known tracking query parameters from a URL.
 */
export function stripTrackingParams(urlString: string): string {
  try {
    const url = new URL(urlString);
    let modified = false;

    const keys = Array.from(url.searchParams.keys());
    for (const key of keys) {
      if (TRACKING_PARAMS.has(key.toLowerCase()) || key.startsWith('utm_')) {
        url.searchParams.delete(key);
        modified = true;
      }
    }

    return modified ? url.toString() : urlString;
  } catch {
    return urlString;
  }
}
